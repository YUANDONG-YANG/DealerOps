"""Generate sql/03_customers_links.sql: `customer` rows and `customer_vehicle` links.

Input is the contract (customers-plan.json, vehicles-plan.json). Output is deterministic.
- Every customer from the plan is inserted, with a postal code whose FSA matches the city.
- Every SOLD vehicle links to exactly one customer of the same dealer; linked_at is on or a few
  days before sold_on (never before added_on).
- A few IN_STOCK vehicles carry deposits / pending deals and are linked within the last 3 weeks.
- Some customers own two vehicles; some own none (prospects).
- customer.created_at precedes the customer's first link.
All references use natural keys: dealer -> contact_email, vehicle -> (dealer, vin),
customer -> (dealer, email). Re-runs are guarded with NOT EXISTS.
"""
import json
import random
from collections import defaultdict
from datetime import date, datetime, timedelta
from pathlib import Path

random.seed(20261016_03)
SEED = Path(__file__).resolve().parent.parent
TODAY = date(2026, 10, 16)

FSAS = {
    "Toronto": ["M4C", "M4E", "M4J", "M4K", "M5V", "M6G", "M6J", "M6K"],
    "Mississauga": ["L5A", "L5B", "L5G", "L5H", "L5M"],
    "Brampton": ["L6P", "L6R", "L6S", "L6T", "L6V", "L6X"],
    "Hamilton": ["L8L", "L8M", "L8P", "L8R", "L9A", "L9C"],
    "Ottawa": ["K1G", "K1H", "K1S", "K1Z", "K2A", "K2B"],
    "London": ["N5V", "N5W", "N5Y", "N6A", "N6C", "N6E"],
    "Kitchener": ["N2A", "N2B", "N2E", "N2G", "N2H", "N2M"],
    "Windsor": ["N8T", "N8W", "N8X", "N9A", "N9B", "N9C"],
    "Barrie": ["L4M", "L4N"],
    "Oshawa": ["L1G", "L1H", "L1J", "L1K"],
    "Sudbury": ["P3A", "P3B", "P3C", "P3E"],
    "Kingston": ["K7K", "K7L", "K7M", "K7P"],
    "Guelph": ["N1E", "N1G", "N1H", "N1K", "N1L"],
    "St. Catharines": ["L2M", "L2N", "L2P", "L2R", "L2S", "L2T"],
    "Peterborough": ["K9H", "K9J", "K9K", "K9L"],
}
LDU_LETTERS = "ABCEGHJKLMNPRSTVWXYZ"
EXTRA_IN_STOCK_LINKS = 9


def q(text):
    return "'" + str(text).replace("\\", "\\\\").replace("'", "''") + "'"


def postal(city):
    fsa = random.choice(FSAS[city])
    return f"{fsa} {random.randint(0, 9)}{random.choice(LDU_LETTERS)}{random.randint(0, 9)}"


def at(day):
    # Ontario business hours (09:00-17:59 EDT) expressed in UTC.
    return datetime(day.year, day.month, day.day, random.randint(13, 21), random.randint(0, 59),
                    random.randint(0, 59))


def ts(value):
    return value.strftime("%Y-%m-%d %H:%M:%S")


def main():
    customers = json.loads((SEED / "contract/customers-plan.json").read_text())
    vehicles = json.loads((SEED / "contract/vehicles-plan.json").read_text())
    by_dealer_c = defaultdict(list)
    by_dealer_v = defaultdict(list)
    dealer_email = {}
    for c in customers:
        by_dealer_c[c["dealer_code"]].append(c)
        dealer_email[c["dealer_code"]] = c["dealer_email"]
    for v in vehicles:
        by_dealer_v[v["dealer_code"]].append(v)
        dealer_email[v["dealer_code"]] = v["dealer_email"]
    codes = sorted(dealer_email)

    # Dealers that also get one deposit / pending-deal link on an in-stock vehicle.
    with_stock = [d for d in codes if any(v["status"] == "IN_STOCK" for v in by_dealer_v[d])]
    deposit_dealers = set(random.sample(with_stock, EXTRA_IN_STOCK_LINKS))

    links = []  # (dealer, customer, vehicle, linked_at)
    for d in codes:
        cs = by_dealer_c[d][:]
        random.shuffle(cs)
        sold = sorted((v for v in by_dealer_v[d] if v["status"] == "SOLD"), key=lambda v: v["sold_on"])
        # Three sales: the first buyer comes back for a second car, leaving room for prospects.
        if len(sold) == 3:
            buyers = [cs[0], cs[1], cs[0]]
        else:
            buyers = cs[:len(sold)]
        for v, c in zip(sold, buyers):
            sold_on = date.fromisoformat(v["sold_on"])
            added_on = date.fromisoformat(v["added_on"])
            day = max(added_on, sold_on - timedelta(days=random.choice([0, 0, 1, 2, 3, 5])))
            links.append((d, c, v, at(day)))
        if d in deposit_dealers:
            stock = [v for v in by_dealer_v[d] if v["status"] == "IN_STOCK"]
            v = random.choice(stock)
            linked_customers = {id(c) for c in buyers}
            fresh = [c for c in cs if id(c) not in linked_customers]
            c = fresh[0] if fresh else cs[0]
            added_on = date.fromisoformat(v["added_on"])
            day = max(added_on, TODAY - timedelta(days=random.randint(1, 20)))
            links.append((d, c, v, at(day)))

    first_link = {}
    for d, c, v, linked_at in links:
        key = (d, c["email"])
        first_link[key] = min(first_link.get(key, linked_at), linked_at)

    out = ["SET NAMES utf8mb4;", "",
           "-- Customers (four per dealership) and customer_vehicle links.",
           "-- Generated by scripts/gen_links.py from contract/*.json; do not hand-edit.", ""]
    for d in codes:
        out.append(f"SET @{d.lower()} = (SELECT id FROM dealer WHERE contact_email = {q(dealer_email[d])});")
    out.append("")

    out.append("-- customer")
    for d in codes:
        var = "@" + d.lower()
        for c in by_dealer_c[d]:
            email = c["email"].strip().lower()
            city = c["home_address"].split(", ")[-2]
            address = f"{c['home_address']} {postal(city)}"
            first = first_link.get((d, c["email"]))
            if first:
                created = at(first.date() - timedelta(days=random.randint(1, 30)))
            else:
                created = at(TODAY - timedelta(days=random.randint(3, 120)))
            out.append(
                "INSERT INTO customer (dealer_id, name, email, phone, home_address, version, created_at, updated_at)\n"
                f"SELECT {var}, {q(c['name'].strip())}, {q(email)}, {q(c['phone'].strip())}, {q(address)}, 0, "
                f"{q(ts(created))}, {q(ts(created))}\n"
                f"FROM DUAL WHERE {var} IS NOT NULL AND NOT EXISTS "
                f"(SELECT 1 FROM customer WHERE dealer_id = {var} AND email = {q(email)});")
    out.append("")

    out.append("-- customer_vehicle")
    for d, c, v, linked_at in links:
        var = "@" + d.lower()
        out.append(
            "INSERT INTO customer_vehicle (dealer_id, customer_id, vehicle_id, linked_at)\n"
            f"SELECT {var}, c.id, v.id, {q(ts(linked_at))}\n"
            f"FROM customer c JOIN vehicle v ON v.dealer_id = c.dealer_id\n"
            f"WHERE c.dealer_id = {var} AND c.email = {q(c['email'].lower())} AND v.vin = {q(v['vin'])}\n"
            "  AND NOT EXISTS (SELECT 1 FROM customer_vehicle cv WHERE cv.vehicle_id = v.id);")
    out.append("")

    (SEED / "sql").mkdir(exist_ok=True)
    (SEED / "sql/03_customers_links.sql").write_text("\n".join(out))
    print(f"customers={len(customers)} links={len(links)} "
          f"sold_links={sum(v['status'] == 'SOLD' for _, _, v, _ in links)}")


if __name__ == "__main__":
    main()
