using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;
using DealerOps.Core.Common.Tenant;

namespace DealerOps.Core.Customer;

/// <summary>
/// A customer-to-vehicle link. Unlinking soft-deletes the row through <see cref="DeletedAt"/>; a vehicle has
/// at most one active link (unique <see cref="ActiveVehicleId"/>).
/// </summary>
[Table("customer_vehicle")]
public class CustomerVehicleEntity : ITenantOwned
{
    [Key]
    [Column("id")]
    [DatabaseGenerated(DatabaseGeneratedOption.Identity)]
    public long Id { get; set; }

    [Column("dealer_id")]
    public long? DealerId { get; set; }

    [Column("customer_id")]
    public long CustomerId { get; set; }

    [Column("vehicle_id")]
    public long VehicleId { get; set; }

    [Column("linked_at")]
    public DateTime LinkedAt { get; set; }

    [Column("deleted_at")]
    public DateTime? DeletedAt { get; set; }

    /// <summary>The vehicle id while the link is active, NULL once unlinked; generated by MySQL.</summary>
    [Column("active_vehicle_id")]
    public long? ActiveVehicleId { get; set; }
}
